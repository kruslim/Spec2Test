"""A profile: one customer's way of receiving verification items. It sets the ID scheme, the
output template (format and columns), the vocabulary, and the fields every item must carry.

Profiles are TOML files; `load_profile` reads one and checks it before anything is
exported, so a typo in a column or placeholder fails at once instead of in the output.
"""

from __future__ import annotations

import string
import tomllib
from enum import StrEnum
from pathlib import Path
from typing import Any, Self

from pydantic import BaseModel, ConfigDict, Field, ValidationError, model_validator

from spec2test.schema import VerificationItemKind


class _Record(BaseModel):
    model_config = ConfigDict(extra="forbid")


class ReviewStatus(StrEnum):
    """An item's latest review decision, or none."""

    ACCEPTED = "accepted"
    EDITED = "edited"
    REJECTED = "rejected"
    UNREVIEWED = "unreviewed"


COLUMNS: dict[str, str] = {
    # Identity and trace.
    "id": "ID",
    "item_id": "Generated ID",
    "kind": "Kind",
    "requirements": "Requirements",
    "section": "Section",
    "page": "Page",
    "method": "Method",
    "strength": "Strength",
    "requirement": "Requirement",
    "quote": "Source quote",
    # Every kind, in one column each.
    "actions": "Procedure",
    "acceptance": "Acceptance criterion",
    # The fields of each kind, empty for the other kinds.
    "inspect": "Inspect",
    "pass_condition": "Pass condition",
    "preconditions": "Preconditions",
    "setup": "Setup",
    "equipment": "Equipment",
    "steps": "Test steps",
    "expected_result": "Expected result",
    "pass_criterion": "Pass criterion",
    "description": "Description",
    "procedure": "Evidence procedure",
    "evidence": "Evidence",
    "acceptance_criterion": "Evidence acceptance",
    # Review and provenance.
    "status": "Review status",
    "reviewer": "Reviewer",
    "note": "Review note",
    "model": "Generated by",
}
"""Every column the core fills, with its default label. `actions` is what to do for any
kind (a checklist's inspection, a test case's steps, an evidence item's procedure or
description) and `acceptance` what passes."""

DEFAULT_COLUMNS = [
    "id",
    "kind",
    "requirements",
    "section",
    "page",
    "method",
    "requirement",
    "actions",
    "acceptance",
    "status",
]

KIND_LABELS = {
    VerificationItemKind.CHECKLIST: "Checklist item",
    VerificationItemKind.TEST_CASE: "Test case",
    VerificationItemKind.EVIDENCE: "Evidence item",
}

PLACEHOLDERS = {
    "item": "the generated item ID",
    "doc": "the document code (`ids.doc`, else the document ID)",
    "kind": "the kind code (`ids.kind_codes`)",
    "section": "the section of the item's first requirement",
    "req": "the ID of the item's first requirement",
    "n": "a running number over all items",
    "n_kind": "a running number per kind",
}


class IdScheme(_Record):
    pattern: str = Field(
        default="{item}",
        description="A Python format string over the placeholders, e.g. '{doc}-{kind}-{n:03}'.",
    )
    doc: str | None = Field(default=None, description="What {doc} stands for.")
    kind_codes: dict[VerificationItemKind, str] = Field(default_factory=dict)
    start: int = Field(default=1, ge=0, description="First value of {n} and {n_kind}.")

    @model_validator(mode="after")
    def _check_pattern(self) -> Self:
        self.kind_codes = {**_KIND_CODES, **self.kind_codes}
        try:
            fields = [f for _, f, _, _ in string.Formatter().parse(self.pattern) if f is not None]
        except ValueError as exc:
            raise ValueError(f"ids.pattern {self.pattern!r}: {exc}") from exc
        unknown = [f for f in fields if f not in PLACEHOLDERS]
        if unknown:
            raise ValueError(
                f"ids.pattern {self.pattern!r}: unknown placeholder(s) "
                f"{', '.join(repr(f) for f in unknown)}; use {', '.join(PLACEHOLDERS)}"
            )
        if not {"item", "n", "req", "n_kind"} & set(fields):
            raise ValueError(
                f"ids.pattern {self.pattern!r} gives every item the same ID; include "
                "{n}, {n_kind}, {req} or {item}"
            )
        try:
            self.pattern.format(**_SAMPLE)
        except (ValueError, TypeError, IndexError, KeyError) as exc:
            raise ValueError(f"ids.pattern {self.pattern!r}: {exc}") from exc
        return self


_KIND_CODES = {
    VerificationItemKind.CHECKLIST: "CL",
    VerificationItemKind.TEST_CASE: "TC",
    VerificationItemKind.EVIDENCE: "EV",
}
_SAMPLE: dict[str, Any] = {
    "item": "TC-1",
    "doc": "doc",
    "kind": "TC",
    "section": "5.1",
    "req": "R-1",
    "n": 1,
    "n_kind": 1,
}


class Vocabulary(_Record):
    """The customer's words for what people read: column headers, item kinds and review
    statuses. Anything left out keeps its default label."""

    columns: dict[str, str] = Field(default_factory=dict)
    kinds: dict[VerificationItemKind, str] = Field(default_factory=dict)
    statuses: dict[ReviewStatus, str] = Field(default_factory=dict)


class Output(_Record):
    format: str = Field(default="csv", description="An exporter: csv, xlsx, markdown, yaml.")
    columns: list[str] = Field(default_factory=lambda: list(DEFAULT_COLUMNS), min_length=1)
    title: str | None = Field(default=None, description="Document heading or sheet name.")
    statuses: list[ReviewStatus] = Field(
        default_factory=lambda: [
            ReviewStatus.ACCEPTED,
            ReviewStatus.EDITED,
            ReviewStatus.UNREVIEWED,
        ],
        min_length=1,
        description="Which items to export, by their review status. Edits are always applied.",
    )
    options: dict[str, Any] = Field(
        default_factory=dict, description="Passed to the exporter as is (for plugins)."
    )


class Profile(_Record):
    name: str = "default"
    description: str = ""
    ids: IdScheme = Field(default_factory=IdScheme)
    output: Output = Field(default_factory=Output)
    vocabulary: Vocabulary = Field(default_factory=Vocabulary)
    required: list[str] = Field(
        default_factory=list,
        description="Columns every exported item must fill. An empty one is written as "
        "'[Label]' and reported; values the source does not give are never invented.",
    )
    values: dict[str, str] = Field(
        default_factory=dict,
        description="Columns of the customer's own with one value for every item, e.g. "
        "program or owner.",
    )

    @model_validator(mode="after")
    def _check_names(self) -> Self:
        custom = set(self.values) | set(self.required)
        clash = sorted(set(self.values) & set(COLUMNS))
        if clash:
            raise ValueError(f"values: {', '.join(clash)} are filled by the core")
        bad = [c for c in custom if not c or c != c.strip()]
        if bad:
            raise ValueError(f"column names must be non-empty and unpadded: {bad!r}")
        known = set(COLUMNS) | custom
        unknown = [c for c in self.output.columns if c not in known]
        if unknown:
            raise ValueError(
                f"output.columns: unknown column(s) {', '.join(unknown)}; a column of your "
                "own needs a value in [values] or a place in `required`"
            )
        dupes = sorted({c for c in self.output.columns if self.output.columns.count(c) > 1})
        if dupes:
            raise ValueError(f"output.columns lists {', '.join(dupes)} more than once")
        if "id" not in self.output.columns:
            raise ValueError("output.columns must include 'id'")
        not_out = [c for c in [*self.required, *self.values] if c not in self.output.columns]
        if not_out:
            raise ValueError(f"{', '.join(not_out)} not in output.columns; add them or drop them")
        unknown = [c for c in self.vocabulary.columns if c not in known]
        if unknown:
            raise ValueError(f"vocabulary.columns: unknown column(s) {', '.join(unknown)}")
        return self

    def label(self, column: str) -> str:
        """What people read as the column's header."""
        if column in self.vocabulary.columns:
            return self.vocabulary.columns[column]
        return COLUMNS.get(column) or column.replace("_", " ").capitalize()

    def kind_label(self, kind: VerificationItemKind) -> str:
        return self.vocabulary.kinds.get(kind) or KIND_LABELS[kind]

    def status_label(self, status: ReviewStatus) -> str:
        return self.vocabulary.statuses.get(status) or status.value


def load_profile(path: str | Path) -> Profile:
    """Read and check a profile TOML file."""
    path = Path(path)
    with path.open("rb") as f:
        data = tomllib.load(f)
    try:
        return Profile.model_validate(data)
    except ValidationError as exc:
        problems = "; ".join(
            ".".join(str(part) for part in e["loc"]) + ": " + e["msg"] if e["loc"] else e["msg"]
            for e in exc.errors()
        )
        raise ValueError(f"{path.name}: {problems.replace('Value error, ', '')}") from exc
